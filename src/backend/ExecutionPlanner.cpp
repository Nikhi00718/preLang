bool isImageInstruction(const Instruction& instruction) {
    switch (instruction.op) {
        case Opcode::LoadImages:
        case Opcode::Resize:
        case Opcode::Grayscale:
        case Opcode::NormalizeImages:
        case Opcode::Compress:
        case Opcode::Convert:
        case Opcode::RemoveCorrupt:
        case Opcode::SaveImages:      return true;
        case Opcode::Check:           return instruction.text == "MATCH_RATE";
        default:                      return false;
    }
}

ExecutionPlanner::ExecutionPlanner(std::filesystem::path outputFolder, std::string sourceName,
                                   const Certificate& certificate)
    : outputFolder_(std::move(outputFolder)), sourceName_(std::move(sourceName)), certificate_(certificate) {}

std::string ExecutionPlanner::generate(const IRProgram& program, const std::string& manifestCode) const {
    const auto uses = [&](auto predicate) { return std::any_of(program.code.begin(), program.code.end(), predicate); };
    const bool tables = uses([](const Instruction& in) { return in.op == Opcode::Load; });
    const bool images = uses([](const Instruction& in) { return in.op == Opcode::LoadImages; });
    const bool letterbox = uses([](const Instruction& in) { return in.op == Opcode::Resize && in.numbers[2] == 1; });
    const bool grayscale = uses([](const Instruction& in) { return in.op == Opcode::Grayscale; });
    const auto loads = [&](TableFormat format) {
        return uses([&](const Instruction& in) {
            return in.op == Opcode::Load && program.tables.at(tableKey(in.dataset, in.table)).format == format;
        });
    };

    std::ostringstream out;
    out << "# Generated by the PrepLang compiler from " << sourceName_ << ". Do not edit.\n"
        << "import io\nimport json\nimport os\nimport sys\nimport zlib\nfrom pathlib import Path\n\n";
    if (images) {
        out << "import cv2\nimport numpy as np\n";
    }
    if (tables) {
        // FILTER and SELECT results are changed later without copying them first.
        // pandas 3 always uses copy-on-write for this; pandas 2 needs to be told.
        out << "import pandas as pd\n\nif int(pd.__version__.split(\".\")[0]) < 3:\n"
            << "    pd.options.mode.copy_on_write = True\n";
    }
    out << "\nHERE = Path(__file__).resolve().parent\n\n\nclass ContractError(Exception):\n    pass\n\n\n"
        << R"(def report(kind, error, trace):
    """A refused input or a broken contract is reported in one line, not as a traceback."""
    if issubclass(kind, ContractError):
        print(f"ContractError: {error}", file=sys.stderr)
    else:
        sys.__excepthook__(kind, error, trace)


sys.excepthook = report

)" << R"(# An input can be given another file or folder when the program is run:
#   py -3 generated.py students=new_students.csv
INPUTS = dict(arg.split("=", 1) for arg in sys.argv[1:] if "=" in arg)
same_input = {}  # input -> True if it is the one the compiler analysed
# For experiments only: PREPLANG_TRUST_INPUTS=1 treats every input as the compiled
# one, so the optimized program runs on it with no admission check or deoptimization.
TRUST_INPUTS = os.environ.get("PREPLANG_TRUST_INPUTS") == "1"


def refuse(path, problem, needed_by):
    raise ContractError(f"{path} is not the input the program was compiled with, and {problem}"
                        + (f"; the compiled program relies on this for {needed_by}" if needed_by else "")
                        + ". Compile the .prep file again for this input.")


)";
    if (tables) {
        out << PandasCodegen::helpers(loads(TableFormat::Csv), loads(TableFormat::Parquet));
    }
    if (uses([](const Instruction& in) { return in.op == Opcode::Plot || in.op == Opcode::Report; })) {
        out << PandasCodegen::chartHelpers();
    }
    if (images) {
        out << OpenCVCodegen::helpers(letterbox, grayscale);
    }
    out << deoptimization(program) << "outputs = []\n\n";

    PandasCodegen pandas(outputFolder_, certificate_);
    OpenCVCodegen opencv(outputFolder_, certificate_);
    for (const Instruction& instruction : program.code) {
        out << "# line " << instruction.line << ": " << instructionText(instruction);
        if (!instruction.speculative) {
            out << '\n'
                << (isImageInstruction(instruction) ? opencv.code(instruction, program)
                                                    : pandas.code(instruction, program))
                << '\n';
            continue;
        }
        // Removed speculatively: it runs only for an admitted input that breaks its
        // item certificate. One that every admitted input keeps is not written at all.
        const ItemCertificate* item = certificate_.item(instruction.proofKey);
        if (!item || item->empty()) {
            out << "  (removed: proven for every admitted input)\n\n";
            continue;
        }
        out << "  (removed unless deoptimized)\n";
        if (isImageInstruction(instruction)) {
            out << opencv.code(instruction, program, instruction.proofKey) << '\n';
            continue;
        }
        std::istringstream lines(pandas.code(instruction, program));
        out << "if deopt(" << pythonString(instruction.proofKey) << "):\n";
        for (std::string line; std::getline(lines, line);) {
            out << "    " << line << '\n';
        }
        out << '\n';
    }
    out << manifestCode;
    return out.str();
}

// The item certificates of the speculatively removed instructions and deopt(),
// which decides once per instruction whether a new input needs it after all.
std::string ExecutionPlanner::deoptimization(const IRProgram& program) const {
    std::string items;
    for (const ItemCertificate& item : certificate_.items) {
        const bool used = std::any_of(program.code.begin(), program.code.end(),
                                      [&](const Instruction& in) { return in.speculative && in.proofKey == item.key; });
        if (item.empty() || !used) {
            continue;
        }
        std::string tables, images;
        for (const TableCertificate& table : item.tables) {
            tables += (tables.empty() ? "" : ", ") + pythonString(table.key) + ": " + PandasCodegen::columnsDict(table);
        }
        for (const ImageCertificate& image : item.images) {
            images +=
                (images.empty() ? "" : ", ") + pythonString(image.dataset) + ": " + OpenCVCodegen::imageDict(image);
        }
        items += "    " + pythonString(item.key) + ": {\"description\": " + pythonString(item.description) +
                 ",\n        \"tables\": {" + tables + "},\n        \"images\": {" + images + "}},\n";
    }
    return "# Speculatively removed checks and operations, with the facts each needs beyond\n"
           "# admission (its item certificate). An admitted input that breaks them runs them after all.\n"
           "ITEMS = {\n" +
           items + "}\n" + R"(ITEM_COLUMNS = {}
for _item in ITEMS.values():
    for _table, _columns in _item["tables"].items():
        ITEM_COLUMNS.setdefault(_table, set()).update(_columns)
input_facts = {}  # new table input -> facts of the columns ITEMS is about
image_facts = {}  # new image folder -> facts of its headers
deoptimized = []  # what ran after all, and why
deopt_cache = {}


def deopt(key):
    """True if an admitted input other than the compiled one breaks the item
    certificate of this removed check or operation, which then runs after all.
    Every other removal stays justified (see the data certificate)."""
    if key not in deopt_cache:
        item, problem = ITEMS[key], ""
        for table, certificate in item["tables"].items():
            if not same_input.get(table, True) and not problem:
                problem = table_problem(input_facts[table], certificate)
        for name, certificate in item["images"].items():
            if not same_input.get(name, True) and not problem:
                problem = image_problem(image_facts[name], certificate)
        deopt_cache[key] = bool(problem)
        if problem:
            deoptimized.append(f"{item['description']}: {problem}")
            print(f"Deoptimized {item['description']}: {problem}")
    return deopt_cache[key]


)";
}

std::vector<std::string> ExecutionPlanner::imagePasses(const IRProgram& program) {
    std::map<std::string, std::vector<std::string>> steps;  // dataset -> operations since LOAD_IMAGES
    std::map<std::string, std::string> format;
    std::vector<std::string> passes;
    for (const Instruction& in : program.code) {
        const std::string mark = in.speculative ? " (if deoptimized)" : "";
        switch (in.op) {
            case Opcode::LoadImages:
                steps[in.dataset].clear();
                format[in.dataset] = "original format";
                break;
            case Opcode::Resize:
                steps[in.dataset].push_back("RESIZE " + std::to_string(in.numbers[0]) + "x" +
                                            std::to_string(in.numbers[1]) + (in.numbers[2] ? " KEEP_ASPECT" : "") +
                                            mark);
                break;
            case Opcode::Grayscale: steps[in.dataset].push_back("GRAYSCALE" + mark); break;
            case Opcode::NormalizeImages:
                steps[in.dataset].push_back("NORMALIZE " + in.values[0].value + ".." + in.values[1].value + mark);
                break;
            case Opcode::RemoveCorrupt: steps[in.dataset].push_back("skip broken files"); break;
            case Opcode::Convert:       format[in.dataset] = in.text + mark; break;
            case Opcode::Compress:      format[in.dataset] += " quality " + std::to_string(in.numbers[0]); break;
            case Opcode::SaveImages:    {
                const size_t files = program.images.at(in.dataset).images.size();
                std::string chain;
                for (const std::string& step : steps[in.dataset]) {
                    chain += step + " -> ";
                }
                passes.push_back((in.numbers[0] ? "SAVE_IMAGE " : "SAVE_IMAGES ") + in.dataset + " (line " +
                                 std::to_string(in.line) + "): 1 streaming pass over " + std::to_string(files) +
                                 " file" + (files == 1 ? "" : "s") + ": read -> " + chain + "write " +
                                 format[in.dataset]);
                break;
            }
            default: break;
        }
    }
    return passes;
}
