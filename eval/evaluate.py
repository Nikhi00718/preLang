def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", action="store_true", help="run the differential test and the census first")
    parser.add_argument("--quick", action="store_true", help="a small differential test and census only")
    args = parser.parse_args()
    if args.quick:
        quick = ROOT / "eval" / "work" / "quick"
        quick.mkdir(parents=True, exist_ok=True)
        env = dict(os.environ, PREPLANG_RESULTS=str(quick), PREPLANG_DIFF_WORK="differential_quick")
        run("compilation/differential.py", "--programs", "200", env=env)
        run("compilation/census.py", "--quick", env=env)
        print(f"Results in {quick}: differential.md, census.md")
        return
    if args.run:
        run("compilation/differential.py", "--programs", "2000")
        run("compilation/census.py")
    text = report(numbers())
    (RESULTS / "evaluation.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
