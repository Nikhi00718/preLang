"""The evaluation in six questions, answered from eval/results/.

    py -3 eval/evaluate.py             # regenerate paper/generated/numbers.tex, write eval/results/evaluation.md
    py -3 eval/evaluate.py --run       # first run the differential test and the census again
    py -3 eval/evaluate.py --quick     # a small differential test and census (minutes, e.g. in Docker),
                                       # written to eval/work/quick/; the committed results are not touched

    1. Correctness              does the compiler produce the right output?
    2. Performance              how much faster or slower is the generated program?
    3. Optimization effectiveness  how much unnecessary work does it eliminate?
    4. Practical usefulness     does it work on real programs and datasets?
    5. Comparison               does it do better than existing tools on comparable tasks?
    6. Overhead                 what compile time, memory and run-time cost does it add?

Every number comes from the same macros as the paper (eval/paper_numbers.py), so the two agree.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval" / "results"
PYTHON = sys.executable


def run(script, *args, env=None):
    print("running", script, *args, flush=True)
    subprocess.run([PYTHON, str(ROOT / "eval" / script), *args], check=True, env=env)


def numbers():
    run("paper_numbers.py")
    text = (ROOT / "paper" / "generated" / "numbers.tex").read_text(encoding="utf-8")
    return {name: value.replace("$", "").replace(r"\,", "") for name, value in
            re.findall(r"\\newcommand\{\\(\w+)\}\{(.*)\}", text)}


