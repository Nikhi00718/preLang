"""Catalog of the real-bug study (RQ6): data-preparation failures reported in GitHub issues.

Protocol (September 2026):
  1. 17 error signatures: the messages Python libraries print for common data-preparation
     failures, chosen before looking at any issue. They include failures PrepLang is not
     designed for (dates, text encodings, sample counts), so the result measures coverage.
  2. For each signature, a GitHub issue search (best match, first 12 results; for signature
     S10, one result per repository, because one project files hundreds of automatic reports).
  3. Every result was read in order. An issue qualifies if the failure happens while a
     program loads, transforms or saves data files (tables, images or other datasets) and the
     issue or its comments show the root cause. At most 3 qualifying issues per signature.
  4. Each qualifying issue gets a verdict:
       compile   PrepLang reports the cause before any data is processed, with no annotation
       contract  PrepLang reports it before any data is processed if the requirement is
                 declared with EXPECT (for example the channel count a model needs)
       design    the failing construct cannot occur in a PrepLang program
       none      not detected, or not expressible in PrepLang (the reason says which)
     Every compile, contract and design verdict has a reproduction in run_realbugs.py that is
     checked against the compiler.
"""

