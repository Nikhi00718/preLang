"""
code_generator.py
=================

Compiler Phase 6 -- Target Code Generation.

Emits executable Python/Pandas source from the (optimised) IR. There is one
emitter per opcode, so the mapping from IR to target code is a table rather
than a tangle of special cases:

    IR_LOAD        d "f.csv"     ->  d = pd.read_csv("f.csv", usecols=[...])
    IR_DROP_NULL   d             ->  d = d.dropna(subset=[...])
    IR_FILL_NULL   d c <- v      ->  d["c"] = d["c"].fillna(v)
    IR_NORMALIZE   d c           ->  d["c"] = (d["c"] - d["c"].mean()) / d["c"].std()
    IR_FILTER      d c op v      ->  d = d[d["c"] op v]
    IR_SELECT      d [a, b]      ->  d = d[["a", "b"]]
    IR_DROP        d [a, b]      ->  d = d.drop(columns=["a", "b"])
    IR_SAVE        d "o.csv"     ->  d.to_csv("o.csv", index=False)
    IR_EXPECT_*                  ->  a call to a generated validation helper

The generated program is ordinary, readable Pandas: it can be saved, read,
modified and run without PrepLang, which is the practical argument for
compiling to source rather than interpreting the IR directly.

Two details are worth noticing in the output:

* ``usecols=`` on ``read_csv`` is the column-pruning optimisation made visible.
* ``dropna(subset=[...])`` carries the live-column set, which is what makes
  pruning semantics-preserving (see :mod:`preplang.optimizer`).
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .ast_nodes import fmt_number
from .ir import IROp, IRProgram

#: Emitted once at the top of every generated program.
PRELUDE = '''"""
Generated by the PrepLang compiler -- do not edit by hand.

This file is ordinary Python/Pandas: it can be run, read and modified without
PrepLang. Every statement below corresponds to one IR instruction; the source
line of the original PrepLang statement is given in the comment.
"""

import pandas as pd


def _contract_report(name, column, description, violations, rows):
    """Print the outcome of one data contract (compiled from an EXPECT)."""
    if violations == 0:
        print(f"[PASS] {name}.{column}: {description} ({rows} rows checked)")
    else:
        print(f"[FAIL] {name}.{column}: {description} -- {violations} violation(s)")


def _expect_type(df, name, column, kind, line):
    series = df[column].dropna()
    if kind == "NUMBER":
        bad = pd.to_numeric(series, errors="coerce").isna().sum()
    elif kind == "BOOLEAN":
        allowed = {"true", "false", "yes", "no", "t", "f", "y", "n"}
        bad = (~series.astype(str).str.lower().isin(allowed)).sum()
    else:
        bad = 0
    _contract_report(name, column, f"every value must be {kind}", int(bad), len(df))
    return int(bad)


def _expect_range(df, name, column, low, high, line):
    series = pd.to_numeric(df[column], errors="coerce")
    bad = ((series < low) | (series > high) | (series.isna() & df[column].notna())).sum()
    _contract_report(name, column, f"{low} <= value <= {high}", int(bad), len(df))
    return int(bad)


def _expect_not_null(df, name, column, line):
    bad = int(df[column].isna().sum())
    _contract_report(name, column, "no value may be missing", bad, len(df))
    return bad
'''


@dataclass
class GeneratedCode:
    """The generated target program plus a little metadata."""

    source: str
    lines: int = 0
    output_files: list[str] = field(default_factory=list)
    optimised: bool = True

    def __str__(self) -> str:  # pragma: no cover - trivial
        return self.source


class CodeGenerator:
    """Turns an IR program into Python/Pandas source code."""

    def __init__(self, include_contracts: bool = True) -> None:
        self.include_contracts = include_contracts

    # ------------------------------------------------------------------
    def generate(self, ir: IRProgram, optimised: bool = True) -> GeneratedCode:
        body: list[str] = []
        outputs: list[str] = []

        for instruction in ir.instructions:
            emitted = self._emit(instruction)
            if emitted is None:
                continue
            body.append(f"# line {instruction.line}: {instruction.op} {instruction.operand_text()}".rstrip())
            body.extend(emitted)
            body.append("")
            if instruction.op is IROp.SAVE:
                outputs.append(str(instruction.args[0]))

        header = PRELUDE
        if not optimised:
            header += "\n# (compiled with optimisation disabled)\n"
        source = header + "\n" + "\n".join(body).rstrip() + "\n"
        return GeneratedCode(
            source=source,
            lines=len(source.splitlines()),
            output_files=outputs,
            optimised=optimised,
        )

    # ------------------------------------------------------------------
    # One emitter per opcode
    # ------------------------------------------------------------------
    def _emit(self, instruction) -> list[str] | None:
        handler = {
            IROp.LOAD: self._load,
            IROp.DROP_NULL: self._drop_null,
            IROp.FILL_NULL: self._fill_null,
            IROp.NORMALIZE: self._normalize,
            IROp.FILTER: self._filter,
            IROp.SELECT: self._select,
            IROp.DROP: self._drop,
            IROp.SAVE: self._save,
            IROp.EXPECT_TYPE: self._expect_type,
            IROp.EXPECT_RANGE: self._expect_range,
            IROp.EXPECT_NOT_NULL: self._expect_not_null,
        }.get(instruction.op)
        return handler(instruction) if handler else None

    def _load(self, instruction) -> list[str]:
        dataset = instruction.dataset
        path = instruction.args[0]
        usecols = instruction.meta.get("usecols")
        if usecols:
            columns = ", ".join(repr(c) for c in usecols)
            return [
                f"{dataset} = pd.read_csv(",
                f"    {path!r},",
                f"    usecols=[{columns}],   # column pruning: "
                f"only the {len(usecols)} required column(s) are read",
                ")",
            ]
        return [f"{dataset} = pd.read_csv({path!r})"]

    def _drop_null(self, instruction) -> list[str]:
        dataset = instruction.dataset
        subset = instruction.meta.get("subset")
        if subset:
            columns = ", ".join(repr(c) for c in subset)
            return [f"{dataset} = {dataset}.dropna(subset=[{columns}])"]
        return [f"{dataset} = {dataset}.dropna()"]

    def _fill_null(self, instruction) -> list[str]:
        dataset = instruction.dataset
        column, value = instruction.args
        return [f"{dataset}[{column!r}] = {dataset}[{column!r}].fillna({value!r})"]

    def _normalize(self, instruction) -> list[str]:
        dataset = instruction.dataset
        column = instruction.args[0]
        return [
            f"{dataset}[{column!r}] = (",
            f"    {dataset}[{column!r}] - {dataset}[{column!r}].mean()",
            f") / {dataset}[{column!r}].std()",
        ]

    def _filter(self, instruction) -> list[str]:
        dataset = instruction.dataset
        column, operator, value = instruction.args
        return [f"{dataset} = {dataset}[{dataset}[{column!r}] {operator} {value!r}]"]

    def _select(self, instruction) -> list[str]:
        dataset = instruction.dataset
        columns = ", ".join(repr(c) for c in instruction.columns)
        return [f"{dataset} = {dataset}[[{columns}]]"]

    def _drop(self, instruction) -> list[str]:
        dataset = instruction.dataset
        columns = ", ".join(repr(c) for c in instruction.columns)
        return [f"{dataset} = {dataset}.drop(columns=[{columns}])"]

    def _save(self, instruction) -> list[str]:
        dataset = instruction.dataset
        path = instruction.args[0]
        return [
            f"{dataset}.to_csv({path!r}, index=False)",
            f"print('wrote', {path!r}, '-', len({dataset}), 'rows x',"
            f" len({dataset}.columns), 'columns')",
        ]

    # -- contracts ------------------------------------------------------
    def _expect_type(self, instruction) -> list[str] | None:
        if not self.include_contracts:
            return None
        dataset = instruction.dataset
        column, kind = instruction.args
        return [
            f"_expect_type({dataset}, {dataset!r}, {column!r}, {kind!r}, {instruction.line})"
        ]

    def _expect_range(self, instruction) -> list[str] | None:
        if not self.include_contracts:
            return None
        dataset = instruction.dataset
        column, low, high = instruction.args
        return [
            f"_expect_range({dataset}, {dataset!r}, {column!r}, "
            f"{fmt_number(low)}, {fmt_number(high)}, {instruction.line})"
        ]

    def _expect_not_null(self, instruction) -> list[str] | None:
        if not self.include_contracts:
            return None
        dataset = instruction.dataset
        column = instruction.args[0]
        return [
            f"_expect_not_null({dataset}, {dataset!r}, {column!r}, {instruction.line})"
        ]


def generate_code(
    ir: IRProgram, optimised: bool = True, include_contracts: bool = True
) -> GeneratedCode:
    """Convenience wrapper around :class:`CodeGenerator`."""
    return CodeGenerator(include_contracts=include_contracts).generate(ir, optimised)
